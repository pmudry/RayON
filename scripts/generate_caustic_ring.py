#!/usr/bin/env python3
"""Generate resources/models/caustic_ring.obj: an open cylinder (no caps), smooth radial normals.

Used as a mirror ring by resources/scenes/22_caustic_ring.yaml: lit from the side, its inner wall
focuses the light into the cusped curve seen at the bottom of a cup (a nephroid).

Usage: python3 scripts/generate_caustic_ring.py [segments]
"""
import math
import os
import sys

RADIUS = 1.0
HEIGHT = 0.45


def main():
    n = int(sys.argv[1]) if len(sys.argv) > 1 else 256
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    path = os.path.join(root, "resources", "models", "caustic_ring.obj")
    with open(path, "w") as f:
        f.write(f"# Open cylinder for the caustic ring scene: radius {RADIUS}, height {HEIGHT}, {n} segments\n")
        f.write("# Generated by scripts/generate_caustic_ring.py\n")
        for i in range(n):
            a = 2.0 * math.pi * i / n
            x, z = RADIUS * math.cos(a), RADIUS * math.sin(a)
            f.write(f"v {x:.6f} 0.000000 {z:.6f}\n")
            f.write(f"v {x:.6f} {HEIGHT:.6f} {z:.6f}\n")
        for i in range(n):
            a = 2.0 * math.pi * i / n
            f.write(f"vn {math.cos(a):.6f} 0.000000 {math.sin(a):.6f}\n")
        for i in range(n):
            j = (i + 1) % n
            b0, t0, b1, t1 = 2 * i + 1, 2 * i + 2, 2 * j + 1, 2 * j + 2
            n0, n1 = i + 1, j + 1
            f.write(f"f {b0}//{n0} {b1}//{n1} {t1}//{n1}\n")
            f.write(f"f {b0}//{n0} {t1}//{n1} {t0}//{n0}\n")
    print(f"Wrote {path} ({2 * n} triangles)")


if __name__ == "__main__":
    main()
